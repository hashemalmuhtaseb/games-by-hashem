import { choiceRound } from "../build";
import type { ModeDefinition } from "../types";
import { customQuestion, customQuestions } from "@/content/custom";

/** Serves reviewed custom questions (editor-written or pipeline-generated) inside a mixed game. */
export function communityMode(slug: string): ModeDefinition {
  return {
    id: "community",
    label: "Community picks",
    kinds: ["choice"],
    description: "Questions written by editors or generated by the content pipeline. Every one passed validation and human review.",
    unavailableReason: () => (customQuestions().length ? null : "No reviewed custom questions are published yet."),
    candidates: () =>
      customQuestions().map((q) => ({ key: q.key, subject: q.key, topic: q.topic, difficulty: q.difficulty, mode: "community", gameSlug: slug, ref: q.key })),
    build(c, ctx) {
      const q = customQuestion(c.ref);
      if (!q) throw new Error("custom question no longer published");
      const r = choiceRound({
        c,
        rng: ctx.rng,
        modeLabel: "Community picks",
        prompt: q.prompt.question,
        timeLimitSec: ctx.timeLimitSec ?? 15,
        correct: { label: q.prompt.correct },
        distractors: q.prompt.wrong.map((label) => ({ label })),
        explanation: q.prompt.explanation,
        source: q.source,
      });
      r.pub.generatedBy = q.origin;
      return r;
    },
  };
}
