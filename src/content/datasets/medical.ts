/**
 * Fictional teaching cases for the medicine games.
 *
 * Every case is invented: no real patient is described. Each one is a classic presentation of a
 * common condition as taught in standard references (NICE Clinical Knowledge Summaries, the MSD/
 * Merck Manual Professional Edition, Oxford Handbook of Clinical Medicine). The `reference` field
 * names where the teaching point can be checked. These cases are for learning and play only and
 * are NOT medical advice. Real patients don't read like textbooks; anyone unwell should see a
 * clinician.
 *
 * Rules enforced by tests/unit/medical.test.ts:
 *  - unique ids; the diagnosis (and its aliases) never appears in any clue text;
 *  - at least three distractors, none equal to the diagnosis;
 *  - explanation, hint and reference are always present.
 */

